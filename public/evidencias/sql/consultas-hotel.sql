-- Oracle Database. Datos ficticios. Importe en unidades monetarias.
-- C01. ¿Qué reservas se registraron desde el 10 de noviembre de 2026?
SELECT ID_RESERVA, FECHA_RESERVA, ID_HUESPED
FROM RESERVA
WHERE FECHA_RESERVA >= DATE '2026-11-10'
ORDER BY FECHA_RESERVA, ID_RESERVA;

-- C02. ¿Quién contrató cada habitación y cuántas noches contrató?
SELECT r.ID_RESERVA, h.NOMBRE, d.ID_HABITACION,
       d.FECHA_ENTRADA, d.FECHA_SALIDA,
       d.FECHA_SALIDA - d.FECHA_ENTRADA AS NOCHES,
       (d.FECHA_SALIDA - d.FECHA_ENTRADA) * d.TARIFA_NOCHE AS IMPORTE
FROM RESERVA r
JOIN HUESPED h ON h.ID_HUESPED = r.ID_HUESPED
JOIN RESERVA_HABITACION d ON d.ID_RESERVA = r.ID_RESERVA
ORDER BY r.ID_RESERVA, d.ID_HABITACION;

-- C03. ¿Qué reservas tienen alojamiento por al menos 300 unidades monetarias?
SELECT ID_RESERVA,
       SUM((FECHA_SALIDA - FECHA_ENTRADA) * TARIFA_NOCHE) AS ALOJAMIENTO
FROM RESERVA_HABITACION
GROUP BY ID_RESERVA
HAVING SUM((FECHA_SALIDA - FECHA_ENTRADA) * TARIFA_NOCHE) >= 300
ORDER BY ID_RESERVA;

-- C04. ¿Qué habitaciones no están ocupadas el 11 de noviembre de 2026?
SELECT h.ID_HABITACION, t.NOMBRE_TIPO, t.CAPACIDAD
FROM HABITACION h
JOIN TIPO_HABITACION t ON t.ID_TIPO = h.ID_TIPO
WHERE NOT EXISTS (
    SELECT 1 FROM RESERVA_HABITACION d
    WHERE d.ID_HABITACION = h.ID_HABITACION
      AND DATE '2026-11-11' >= d.FECHA_ENTRADA
      AND DATE '2026-11-11' < d.FECHA_SALIDA
)
ORDER BY h.ID_HABITACION;

-- C05. ¿Cuánto debe pagar cada reserva, sumando alojamiento y servicios sin duplicarlos?
WITH a AS (
    SELECT ID_RESERVA,
           SUM((FECHA_SALIDA - FECHA_ENTRADA) * TARIFA_NOCHE) AS ALOJAMIENTO
    FROM RESERVA_HABITACION GROUP BY ID_RESERVA
), s AS (
    SELECT ID_RESERVA, SUM(CANTIDAD * PRECIO_UNITARIO) AS SERVICIOS
    FROM CONSUMO GROUP BY ID_RESERVA
)
SELECT r.ID_RESERVA, NVL(a.ALOJAMIENTO,0) AS ALOJAMIENTO,
       NVL(s.SERVICIOS,0) AS SERVICIOS,
       NVL(a.ALOJAMIENTO,0) + NVL(s.SERVICIOS,0) AS TOTAL_ESTIMADO
FROM RESERVA r
LEFT JOIN a ON a.ID_RESERVA = r.ID_RESERVA
LEFT JOIN s ON s.ID_RESERVA = r.ID_RESERVA
ORDER BY r.ID_RESERVA;

-- C06. ¿Cuáles reservas todavía no tienen factura?
SELECT r.ID_RESERVA, h.NOMBRE
FROM RESERVA r
JOIN HUESPED h ON h.ID_HUESPED = r.ID_HUESPED
WHERE NOT EXISTS (SELECT 1 FROM FACTURA f WHERE f.ID_RESERVA = r.ID_RESERVA)
ORDER BY r.ID_RESERVA;

-- C07. ¿Qué huéspedes realizaron más de una reserva?
SELECT h.ID_HUESPED, h.NOMBRE, COUNT(*) AS RESERVAS
FROM HUESPED h
JOIN RESERVA r ON r.ID_HUESPED = h.ID_HUESPED
GROUP BY h.ID_HUESPED, h.NOMBRE
HAVING COUNT(*) > 1
ORDER BY RESERVAS DESC, h.ID_HUESPED;

-- C08. ¿Cuántas unidades de cada servicio se consumieron y cuánto representan?
SELECT s.ID_SERVICIO, s.NOMBRE_SERVICIO, SUM(c.CANTIDAD) AS UNIDADES,
       SUM(c.CANTIDAD * c.PRECIO_UNITARIO) AS IMPORTE
FROM SERVICIO s
JOIN CONSUMO c ON c.ID_SERVICIO = s.ID_SERVICIO
GROUP BY s.ID_SERVICIO, s.NOMBRE_SERVICIO
ORDER BY s.ID_SERVICIO;

-- C09. ¿Se reconstruyen exactamente las seis filas atómicas de reservas de la etapa 1FN?
SELECT r.ID_RESERVA, r.FECHA_RESERVA, h.ID_HUESPED, h.NOMBRE, h.EMAIL,
       d.ID_HABITACION, d.FECHA_ENTRADA, d.FECHA_SALIDA, d.TARIFA_NOCHE
FROM RESERVA r
JOIN HUESPED h ON h.ID_HUESPED = r.ID_HUESPED
JOIN RESERVA_HABITACION d ON d.ID_RESERVA = r.ID_RESERVA
ORDER BY r.ID_RESERVA, d.ID_HABITACION;
