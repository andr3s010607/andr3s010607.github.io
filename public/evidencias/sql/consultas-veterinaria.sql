-- Oracle Database. Datos ficticios administrativos; importes en unidades monetarias.
-- Ejecutar ddl.sql y datos.sql previamente.
-- 1. ¿Qué consultas se realizaron del 5 al 12 de noviembre de 2026?
SELECT ID_CONSULTA, FECHA_CONSULTA, MOTIVO FROM CONSULTA
WHERE FECHA_CONSULTA >= DATE '2026-11-05' AND FECHA_CONSULTA < DATE '2026-11-13'
ORDER BY FECHA_CONSULTA, ID_CONSULTA;

-- 2. ¿Quién es el propietario y qué profesional atendió cada consulta?
SELECT c.ID_CONSULTA, m.NOMBRE_MASCOTA, p.NOMBRE_PROPIETARIO, v.NOMBRE_VETERINARIO
FROM CONSULTA c JOIN MASCOTA m ON m.ID_MASCOTA = c.ID_MASCOTA
JOIN PROPIETARIO p ON p.ID_PROPIETARIO = m.ID_PROPIETARIO
JOIN VETERINARIO v ON v.ID_VETERINARIO = c.ID_VETERINARIO
ORDER BY c.ID_CONSULTA;

-- 3. ¿Qué importe suman los servicios de cada consulta?
SELECT c.ID_CONSULTA, NVL(SUM(ct.UNIDADES * ct.PRECIO_APLICADO), 0) AS IMPORTE
FROM CONSULTA c LEFT JOIN CONSULTA_TRATAMIENTO ct ON ct.ID_CONSULTA = c.ID_CONSULTA
GROUP BY c.ID_CONSULTA ORDER BY c.ID_CONSULTA;

-- 4. ¿Qué mascotas han tenido al menos dos consultas?
SELECT m.ID_MASCOTA, m.NOMBRE_MASCOTA, COUNT(*) AS NUM_CONSULTAS
FROM MASCOTA m JOIN CONSULTA c ON c.ID_MASCOTA = m.ID_MASCOTA
GROUP BY m.ID_MASCOTA, m.NOMBRE_MASCOTA HAVING COUNT(*) >= 2 ORDER BY m.ID_MASCOTA;

-- 5. ¿Qué tratamientos tienen precio de catálogo superior al promedio?
SELECT ID_TRATAMIENTO, DESCRIPCION, PRECIO_CATALOGO FROM TRATAMIENTO
WHERE PRECIO_CATALOGO > (SELECT AVG(PRECIO_CATALOGO) FROM TRATAMIENTO)
ORDER BY ID_TRATAMIENTO;

-- 6. ¿Qué profesional supervisa a cada veterinario que tiene supervisor?
SELECT s.NOMBRE_VETERINARIO AS SUPERVISOR, v.NOMBRE_VETERINARIO AS SUPERVISADO
FROM VETERINARIO s JOIN VETERINARIO v ON v.ID_SUPERVISOR = s.ID_VETERINARIO
ORDER BY v.ID_VETERINARIO;

-- 7. ¿Cómo se reconstruye cada ficha inicial de mascota desde 3FN?
SELECT m.ID_MASCOTA, m.NOMBRE_MASCOTA, m.FECHA_NACIMIENTO, m.ID_ESPECIE,
       m.ID_PROPIETARIO, e.NOMBRE_ESPECIE, p.DOCUMENTO, p.NOMBRE_PROPIETARIO, p.TELEFONO
FROM MASCOTA m JOIN ESPECIE e ON e.ID_ESPECIE = m.ID_ESPECIE
JOIN PROPIETARIO p ON p.ID_PROPIETARIO = m.ID_PROPIETARIO
ORDER BY m.ID_MASCOTA;

-- 8. ¿Cómo se reconstruye CONSULTA_SERVICIO_1FN desde 3FN?
SELECT c.ID_CONSULTA, c.ID_MASCOTA, c.ID_VETERINARIO, c.FECHA_CONSULTA, c.MOTIVO,
       t.ID_TRATAMIENTO, t.DESCRIPCION, t.PRECIO_CATALOGO,
       ct.UNIDADES, ct.PRECIO_APLICADO, ct.OBSERVACION
FROM CONSULTA c JOIN CONSULTA_TRATAMIENTO ct ON ct.ID_CONSULTA = c.ID_CONSULTA
JOIN TRATAMIENTO t ON t.ID_TRATAMIENTO = ct.ID_TRATAMIENTO
ORDER BY c.ID_CONSULTA, t.ID_TRATAMIENTO;

-- 9. ¿Cuál es la edad de cada mascota a 20 de noviembre de 2026?
SELECT ID_MASCOTA, NOMBRE_MASCOTA,
       TRUNC(MONTHS_BETWEEN(DATE '2026-11-20', FECHA_NACIMIENTO) / 12) AS EDAD
FROM MASCOTA ORDER BY ID_MASCOTA;

-- 10. ¿Cuántas consultas realizó cada veterinario?
SELECT v.ID_VETERINARIO, v.NOMBRE_VETERINARIO, COUNT(c.ID_CONSULTA) AS NUM_CONSULTAS
FROM VETERINARIO v LEFT JOIN CONSULTA c ON c.ID_VETERINARIO = v.ID_VETERINARIO
GROUP BY v.ID_VETERINARIO, v.NOMBRE_VETERINARIO ORDER BY v.ID_VETERINARIO;
