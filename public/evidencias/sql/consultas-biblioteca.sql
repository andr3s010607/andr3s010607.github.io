-- 1. ¿Qué ediciones contienen la palabra "datos" en el título?
SELECT ID_LIBRO, ISBN, TITULO FROM LIBRO
WHERE UPPER(TITULO) LIKE '%DATOS%' ORDER BY ID_LIBRO;

-- 2. ¿Qué copias están pendientes y quién es responsable?
SELECT p.ID_PRESTAMO, s.NOMBRES, s.APELLIDOS,
       d.ID_LIBRO, d.NRO_EJEMPLAR, l.TITULO, p.FECHA_LIMITE
FROM PRESTAMO p JOIN SOCIO s ON s.ID_SOCIO = p.ID_SOCIO
JOIN PRESTAMO_EJEMPLAR d ON d.ID_PRESTAMO = p.ID_PRESTAMO
JOIN EJEMPLAR e ON e.ID_LIBRO = d.ID_LIBRO AND e.NRO_EJEMPLAR = d.NRO_EJEMPLAR
JOIN LIBRO l ON l.ID_LIBRO = e.ID_LIBRO
WHERE d.FECHA_DEVOLUCION IS NULL
ORDER BY p.ID_PRESTAMO, d.ID_LIBRO, d.NRO_EJEMPLAR;

-- 3. ¿Qué socios han realizado al menos dos préstamos?
SELECT s.ID_SOCIO, s.NOMBRES, COUNT(p.ID_PRESTAMO) AS NUM_PRESTAMOS
FROM SOCIO s JOIN PRESTAMO p ON p.ID_SOCIO = s.ID_SOCIO
GROUP BY s.ID_SOCIO, s.NOMBRES
HAVING COUNT(p.ID_PRESTAMO) >= 2 ORDER BY s.ID_SOCIO;

-- 4. ¿Qué ediciones nunca han sido prestadas?
SELECT l.ID_LIBRO, l.TITULO FROM LIBRO l
WHERE NOT EXISTS (SELECT 1 FROM PRESTAMO_EJEMPLAR d WHERE d.ID_LIBRO = l.ID_LIBRO)
ORDER BY l.ID_LIBRO;

-- 5. ¿Qué socios recomendaron a otros socios?
SELECT r.ID_SOCIO AS ID_RECOMENDADOR, r.NOMBRES AS RECOMENDADOR,
       s.ID_SOCIO AS ID_RECOMENDADO, s.NOMBRES AS RECOMENDADO
FROM SOCIO r JOIN SOCIO s ON s.ID_RECOMENDADOR = r.ID_SOCIO
ORDER BY r.ID_SOCIO, s.ID_SOCIO;

-- 6. ¿Qué ediciones tienen varios autores?
SELECT l.ID_LIBRO, l.TITULO, COUNT(*) AS NUM_AUTORES
FROM LIBRO l JOIN AUTORIA a ON a.ID_LIBRO = l.ID_LIBRO
GROUP BY l.ID_LIBRO, l.TITULO HAVING COUNT(*) > 1 ORDER BY l.ID_LIBRO;

-- 7. ¿Cómo se reconstruye cada fila de PRESTAMO_1FN desde 3FN?
SELECT p.ID_PRESTAMO, p.ID_SOCIO, p.FECHA_SALIDA, p.FECHA_LIMITE,
       d.ID_LIBRO, d.NRO_EJEMPLAR, d.FECHA_DEVOLUCION
FROM PRESTAMO p JOIN PRESTAMO_EJEMPLAR d ON d.ID_PRESTAMO = p.ID_PRESTAMO
ORDER BY p.ID_PRESTAMO, d.ID_LIBRO, d.NRO_EJEMPLAR;

-- 8. ¿Cuántos ejemplares contiene cada préstamo (atributo derivado)?
SELECT p.ID_PRESTAMO, COUNT(*) AS TOTAL_EJEMPLARES
FROM PRESTAMO p JOIN PRESTAMO_EJEMPLAR d ON d.ID_PRESTAMO = p.ID_PRESTAMO
GROUP BY p.ID_PRESTAMO ORDER BY p.ID_PRESTAMO;

-- 9. ¿Qué copias están disponibles físicamente y sin préstamo abierto?
SELECT e.ID_LIBRO, e.NRO_EJEMPLAR FROM EJEMPLAR e
WHERE e.ESTADO_FISICO = 'EN_SERVICIO'
AND NOT EXISTS (SELECT 1 FROM PRESTAMO_EJEMPLAR d
                WHERE d.ID_LIBRO = e.ID_LIBRO AND d.NRO_EJEMPLAR = e.NRO_EJEMPLAR
                  AND d.FECHA_DEVOLUCION IS NULL)
ORDER BY e.ID_LIBRO, e.NRO_EJEMPLAR;

-- 10. ¿Cómo se reconstruye LIBRO_AUTOR_1FN desde 3FN?
SELECT l.ID_LIBRO, l.ISBN, l.TITULO, l.ID_EDITORIAL, e.NOMBRE_EDITORIAL,
       a.ID_AUTOR, a.NOMBRE_AUTOR
FROM LIBRO l JOIN EDITORIAL e ON e.ID_EDITORIAL = l.ID_EDITORIAL
JOIN AUTORIA la ON la.ID_LIBRO = l.ID_LIBRO
JOIN AUTOR a ON a.ID_AUTOR = la.ID_AUTOR
ORDER BY l.ID_LIBRO, a.ID_AUTOR;
