-- Oracle Database. Datos ficticios. Importe en unidades monetarias.
-- C01. ¿Qué productos tienen un precio de lista de al menos 3?
SELECT ID_PRODUCTO, NOMBRE_PRODUCTO, PRECIO_LISTA
FROM PRODUCTO
WHERE PRECIO_LISTA >= 3
ORDER BY PRECIO_LISTA DESC, ID_PRODUCTO;

-- C02. ¿Qué compró cada cliente, con cantidades y precio histórico?
SELECT v.ID_VENTA,
       CASE WHEN c.TIPO_CLIENTE = 'N'
            THEN n.NOMBRES || ' ' || n.APELLIDOS
            ELSE j.RAZON_SOCIAL END AS CLIENTE,
       p.NOMBRE_PRODUCTO, d.CANTIDAD, d.PRECIO_UNITARIO,
       d.CANTIDAD * d.PRECIO_UNITARIO AS IMPORTE
FROM VENTA v
JOIN CLIENTE c ON c.ID_CLIENTE = v.ID_CLIENTE
LEFT JOIN NATURAL n ON n.ID_CLIENTE = c.ID_CLIENTE
LEFT JOIN JURIDICO j ON j.ID_CLIENTE = c.ID_CLIENTE
JOIN DETALLE_VENTA d ON d.ID_VENTA = v.ID_VENTA
JOIN PRODUCTO p ON p.ID_PRODUCTO = d.ID_PRODUCTO
ORDER BY v.ID_VENTA, p.ID_PRODUCTO;

-- C03. ¿Qué ventas superan 20 unidades monetarias?
SELECT ID_VENTA, SUM(CANTIDAD * PRECIO_UNITARIO) AS TOTAL_VENTA
FROM DETALLE_VENTA
GROUP BY ID_VENTA
HAVING SUM(CANTIDAD * PRECIO_UNITARIO) > 20
ORDER BY ID_VENTA;

-- C04. ¿Qué proveedores ofrecen cada producto y a qué costo actual?
SELECT p.ID_PRODUCTO, p.NOMBRE_PRODUCTO, pr.NOMBRE_PROVEEDOR, s.COSTO
FROM SUMINISTRO s
JOIN PRODUCTO p ON p.ID_PRODUCTO = s.ID_PRODUCTO
JOIN PROVEEDOR pr ON pr.ID_PROVEEDOR = s.ID_PROVEEDOR
ORDER BY p.ID_PRODUCTO, s.COSTO, pr.ID_PROVEEDOR;

-- C05. ¿Qué productos tienen precio de lista superior al promedio del catálogo?
SELECT ID_PRODUCTO, NOMBRE_PRODUCTO, PRECIO_LISTA
FROM PRODUCTO
WHERE PRECIO_LISTA > (SELECT AVG(PRECIO_LISTA) FROM PRODUCTO)
ORDER BY ID_PRODUCTO;

-- C06. ¿Qué clientes registrados aún no han comprado?
SELECT c.ID_CLIENTE, c.EMAIL
FROM CLIENTE c
WHERE NOT EXISTS (SELECT 1 FROM VENTA v WHERE v.ID_CLIENTE = c.ID_CLIENTE)
ORDER BY c.ID_CLIENTE;

-- C07. ¿Cuál es el menor costo cotizado para cada producto?
SELECT p.ID_PRODUCTO, p.NOMBRE_PRODUCTO, MIN(s.COSTO) AS MENOR_COSTO
FROM PRODUCTO p
JOIN SUMINISTRO s ON s.ID_PRODUCTO = p.ID_PRODUCTO
GROUP BY p.ID_PRODUCTO, p.NOMBRE_PRODUCTO
ORDER BY p.ID_PRODUCTO;

-- C08. ¿Se reconstruyen las cuatro filas de OFERTA_1FN sin pérdida?
SELECT p.ID_PRODUCTO, p.NOMBRE_PRODUCTO, p.ID_CATEGORIA,
       c.NOMBRE_CATEGORIA, p.PRECIO_LISTA, s.ID_PROVEEDOR, s.COSTO
FROM PRODUCTO p
JOIN CATEGORIA c ON c.ID_CATEGORIA = p.ID_CATEGORIA
JOIN SUMINISTRO s ON s.ID_PRODUCTO = p.ID_PRODUCTO
ORDER BY p.ID_PRODUCTO, s.ID_PROVEEDOR;

-- C09. ¿Se reconstruyen las seis filas de VENTA_LINEA_1FN sin pérdida?
SELECT v.ID_VENTA, v.FECHA_VENTA, v.ID_CLIENTE,
       d.ID_PRODUCTO, d.CANTIDAD, d.PRECIO_UNITARIO
FROM VENTA v
JOIN DETALLE_VENTA d ON d.ID_VENTA = v.ID_VENTA
ORDER BY v.ID_VENTA, d.ID_PRODUCTO;

-- C10. ¿Existen clientes que incumplan la especialización total/exclusiva o su discriminador?
SELECT c.ID_CLIENTE, c.TIPO_CLIENTE
FROM CLIENTE c
LEFT JOIN NATURAL n ON n.ID_CLIENTE = c.ID_CLIENTE
LEFT JOIN JURIDICO j ON j.ID_CLIENTE = c.ID_CLIENTE
WHERE (n.ID_CLIENTE IS NULL AND j.ID_CLIENTE IS NULL)
   OR (n.ID_CLIENTE IS NOT NULL AND j.ID_CLIENTE IS NOT NULL)
   OR (c.TIPO_CLIENTE = 'N' AND n.ID_CLIENTE IS NULL)
   OR (c.TIPO_CLIENTE = 'J' AND j.ID_CLIENTE IS NULL)
ORDER BY c.ID_CLIENTE;
